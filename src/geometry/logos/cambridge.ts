export const sdCambridge = (p: Vec2): number => {
  let d = 1000;

  lines.forEach(([p1, p2]) => {
    d = sdBoolean(d, Math.abs(sdCurtailedLine(p, p1, p2)));
  });
  circles.forEach(([c, r]) => {
    d = sdBoolean(d, Math.abs(sdCircle(p, c, r)));
  });
  arcs.forEach(([p1, p2, p3]) => {
    d = sdBoolean(d, Math.abs(sdCircleSegment(p, p1, p3, p2)));
  });

  return d;
};

